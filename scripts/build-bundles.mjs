#!/usr/bin/env node
/**
 * build-bundles.mjs — generate ready-to-copy, PROJECT-LEVEL bundles per AI agent.
 *
 * Source of truth stays skills/ + commands/ + agents/. This script renders that source
 * into one folder per agent under bundles/, each shaped exactly like the folder a
 * developer drops into their own plugin repo. No global config is touched.
 *
 * Every bundle is generated. Never hand-edit a file under bundles/ — edit the source and
 * re-run this. `verify.mjs` fails if the two drift apart.
 *
 * Usage:
 *   node scripts/build-bundles.mjs            build all
 *   node scripts/build-bundles.mjs --check    fail if bundles are stale (used by verify)
 *
 * Exit: 0 ok · 1 stale (with --check)
 */
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import crypto from "node:crypto";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const BUNDLES = path.join(ROOT, "bundles");
const checkOnly = process.argv.includes("--check");

const read = (p) => { try { return fs.readFileSync(p, "utf8"); } catch { return null; } };
const ls = (p) => { try { return fs.readdirSync(p, { withFileTypes: true }); } catch { return []; } };

function split(src) {
  if (!src || !src.startsWith("---")) return { fm: {}, body: src || "" };
  const end = src.indexOf("\n---", 3);
  if (end === -1) return { fm: {}, body: src };
  const fm = {};
  // Strip CR before parsing. On a CRLF checkout every value fails to match — JS `.` does
  // not match `\r` — so descriptions read as absent and every command and persona gets
  // silently skipped, producing bundles with none of them.
  for (const line of src.slice(3, end).replace(/\r/g, "").split("\n")) {
    const m = line.match(/^([A-Za-z_][A-Za-z0-9_-]*)\s*:\s*(.*)$/);
    if (!m) continue;
    let v = m[2].trim();
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) v = v.slice(1, -1);
    fm[m[1]] = v;
  }
  return { fm, body: src.slice(end + 4).replace(/^[\r\n]+/, "") };
}

const yamlStr = (s) => '"' + String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';

/**
 * Each agent keeps skills at a different project-relative path, so the scanner command
 * baked into the docs must be rewritten per bundle. A path that is right for Claude Code
 * is wrong for Cursor, and a wrong path fails on the first step of every task.
 */
const SCANNER_RE = /(?:~\/\.claude|\.claude|\.cursor|\.codex|\.agent)?\/?skills\/wp-context-discovery\/scripts\/plugin_context\.mjs/g;

const TARGETS = {
  claude: {
    label: "Claude Code",
    copyInto: "<your-plugin>/.claude/",
    skillsDir: "skills",
    scanner: ".claude/skills/wp-context-discovery/scripts/plugin_context.mjs",
    commands: "native",   // commands/*.md -> /name
    personas: "native",   // agents/*.md
    verified: true,
  },
  cursor: {
    label: "Cursor",
    copyInto: "<your-plugin>/.cursor/",
    skillsDir: "skills",
    scanner: ".cursor/skills/wp-context-discovery/scripts/plugin_context.mjs",
    commands: "skill",    // skill with disable-model-invocation: true -> /name
    personas: "skill",
    verified: true,
  },
  codex: {
    label: "Codex",
    copyInto: "<your-plugin>/.codex/",
    skillsDir: "skills",
    scanner: ".codex/skills/wp-context-discovery/scripts/plugin_context.mjs",
    commands: "prompt",   // prompts/*.md -> /prompts:name
    personas: "skill",
    verified: false,
  },
  antigravity: {
    label: "Antigravity",
    copyInto: "<your-plugin>/.agent/",
    skillsDir: "skills",
    scanner: ".agent/skills/wp-context-discovery/scripts/plugin_context.mjs",
    commands: "workflow", // workflows/*.md -> /name
    personas: "skill",
    verified: false,
  },
};

const GEN = (src) => `<!-- Generated by wp-custom-agent-skills scripts/build-bundles.mjs from ${src}. Do not edit here; edit the source and rebuild. -->`;

const files = new Map(); // relative path under bundles/ -> content

function emit(rel, content) {
  files.set(rel.split(path.sep).join("/"), content);
}

/** Copy a skill directory into a bundle, rewriting the scanner path for that agent. */
function emitSkillTree(target, key, srcDir, destPrefix) {
  for (const e of ls(srcDir)) {
    const src = path.join(srcDir, e.name);
    const rel = `${destPrefix}/${e.name}`;
    if (e.isDirectory()) {
      emitSkillTree(target, key, src, rel);
    } else {
      let content = read(src);
      if (content === null) continue;
      if (e.name.endsWith(".md")) content = content.replace(SCANNER_RE, target.scanner);
      emit(rel, content);
    }
  }
}

// ---------- build ----------
/**
 * Which skills are OURS to redistribute?
 *
 * Answered from git, not from a manifest file. Upstream WordPress skills are copied into
 * skills/ for local use and are gitignored, so "tracked by git" is exactly "ours".
 *
 * The earlier version excluded skills listed in vendor-manifest.json, which failed OPEN:
 * delete or never create that file and all 18 upstream skills silently landed in the
 * bundles and got committed. A rule protecting someone else's copyright must fail closed,
 * so if git cannot answer, this refuses to build rather than guessing.
 */
function ownedSkills() {
  const all = ls(path.join(ROOT, "skills")).filter((e) => e.isDirectory()).map((e) => e.name);

  const res = spawnSync("git", ["ls-files", "skills"], { cwd: ROOT, encoding: "utf8" });
  if (res.status !== 0 || !res.stdout.trim()) {
    console.error(
      "\nCannot determine which skills are ours: `git ls-files skills` failed.\n" +
      "Refusing to build rather than risk bundling upstream skills we do not redistribute.\n" +
      "Run this inside the git repo, or commit the skills first.\n"
    );
    process.exit(2);
  }

  const tracked = new Set(
    res.stdout.split("\n").map((l) => l.trim()).filter(Boolean)
      .map((l) => l.split("/")[1])       // skills/<name>/...
      .filter(Boolean)
  );

  const excluded = all.filter((n) => !tracked.has(n));
  if (excluded.length) {
    console.log(`  excluding ${excluded.length} untracked (upstream) skills from bundles`);
  }
  return all.filter((n) => tracked.has(n));
}

const srcSkills = ownedSkills();
const srcCommands = ls(path.join(ROOT, "commands")).filter((e) => e.name.endsWith(".md")).map((e) => e.name);
const srcAgents = ls(path.join(ROOT, "agents")).filter((e) => e.name.endsWith(".md")).map((e) => e.name);

for (const [key, target] of Object.entries(TARGETS)) {
  // 1. skills — identical everywhere except the baked scanner path
  for (const s of srcSkills) {
    emitSkillTree(target, key, path.join(ROOT, "skills", s), `${key}/${target.skillsDir}/${s}`);
  }

  // 2. commands
  for (const f of srcCommands) {
    const { fm, body } = split(read(path.join(ROOT, "commands", f)));
    const name = path.basename(f, ".md");
    const fixed = body.replace(SCANNER_RE, target.scanner);
    if (!fm.description) continue;

    if (target.commands === "native") {
      emit(`${key}/commands/${f}`, `---\ndescription: ${fm.description}\n---\n\n${fixed}`);
    } else if (target.commands === "skill") {
      // Cursor: a skill that only appears when you type /name
      emit(
        `${key}/skills/${name}/SKILL.md`,
        `---\nname: ${name}\ndescription: ${yamlStr(fm.description)}\ndisable-model-invocation: true\n---\n\n${GEN(`commands/${f}`)}\n\n# /${name}\n\n${fixed}`
      );
    } else if (target.commands === "prompt") {
      // Codex custom prompts support description + argument-hint and $ARGUMENTS natively.
      emit(
        `${key}/prompts/${f}`,
        `---\ndescription: ${fm.description}\nargument-hint: "[target — a path, a diff, or a description]"\n---\n\n${GEN(`commands/${f}`)}\n\n${fixed}`
      );
    } else if (target.commands === "workflow") {
      // Antigravity workflows are saved prompts triggered with /.
      emit(
        `${key}/workflows/${f}`,
        `---\ndescription: ${fm.description}\n---\n\n${GEN(`commands/${f}`)}\n\n# ${name}\n\n${fixed}`
      );
    }
  }

  // 3. personas
  for (const f of srcAgents) {
    const { fm, body } = split(read(path.join(ROOT, "agents", f)));
    const name = fm.name || path.basename(f, ".md");
    const fixed = body.replace(SCANNER_RE, target.scanner);
    if (!fm.description) continue;

    if (target.personas === "native") {
      emit(`${key}/agents/${f}`, `---\nname: ${name}\ndescription: ${fm.description}\n---\n\n${fixed}`);
    } else {
      emit(
        `${key}/skills/${name}/SKILL.md`,
        `---\nname: ${name}\ndescription: ${yamlStr(fm.description)}\ndisable-model-invocation: true\n---\n\n${GEN(`agents/${f}`)}\n\n${fixed}`
      );
    }
  }

  // 4. per-bundle README
  const cmdLine = {
    native: "commands/  ->  type /wp-spec in chat",
    skill: "skills/ (disable-model-invocation)  ->  type /wp-spec in chat",
    prompt: "prompts/  ->  type /prompts:wp-spec in chat",
    workflow: "workflows/  ->  type /wp-spec in chat",
  }[target.commands];

  emit(
    `${key}/README.md`,
    `# wp-custom-agent-skills — ${target.label} bundle

Generated. Do not edit files here; edit the source in \`skills/\`, \`commands/\`, \`agents/\`
at the repo root and run \`node scripts/build-bundles.mjs\`.

## Install into your plugin

Copy the **contents of this folder** into \`${target.copyInto}\` in your WordPress plugin repo:

\`\`\`
${target.copyInto}
${["skills/", target.commands === "native" ? "commands/" : target.commands === "prompt" ? "prompts/" : target.commands === "workflow" ? "workflows/" : null, target.personas === "native" ? "agents/" : null]
  .filter(Boolean).map((x) => "  " + x).join("\n")}
\`\`\`

Commit it, and every developer on that repo gets the same workflow — no per-machine setup.

## How commands work here

${cmdLine}

## The official WordPress skills (optional but recommended)

This bundle contains the ${target.label} workflow layer only. The official WordPress
knowledge skills (hooks, REST, blocks, WP-CLI, Playground) are **not** included — they are
someone else's work and we ship no redistribution terms for them.

To add them:

\`\`\`bash
git clone https://github.com/WordPress/agent-skills
cp -r agent-skills/skills/* ${target.copyInto}skills/
\`\`\`

Without them everything still runs; the skills fall back to general WordPress practice and
say so rather than pretending.

## The scanner

Skills invoke the deterministic plugin scanner at:

\`\`\`
${target.scanner}
\`\`\`

That path is baked for this bundle's layout. Requires Node; no PHP needed to run it.

${target.verified
  ? "## Status\n\nFormat verified against this tool's published documentation."
  : `## Status — UNVERIFIED\n\nThis bundle follows ${target.label}'s documented layout, but has **not** been\nconfirmed by loading it in ${target.label}. Treat it as a starting point: if the\ncommands do not appear, check that tool's current docs for the directory it reads and\nadjust \`TARGETS\` in \`scripts/build-bundles.mjs\`.`}
`
  );
}

// ---------- write or check ----------
const hash = (s) => crypto.createHash("sha1").update(s).digest("hex");

if (checkOnly) {
  const stale = [];
  for (const [rel, content] of files) {
    const onDisk = read(path.join(BUNDLES, rel));
    if (onDisk === null || hash(onDisk) !== hash(content)) stale.push(rel);
  }
  // Also catch files on disk that the source no longer produces.
  const walk = (dir, base = "") => {
    for (const e of ls(dir)) {
      const rel = base ? `${base}/${e.name}` : e.name;
      if (e.isDirectory()) walk(path.join(dir, e.name), rel);
      else if (!files.has(rel)) stale.push(`${rel} (orphaned)`);
    }
  };
  if (fs.existsSync(BUNDLES)) walk(BUNDLES);

  if (stale.length) {
    console.error(`\nbundles/ is STALE — ${stale.length} file(s) differ from source:`);
    for (const s of stale.slice(0, 10)) console.error(`  ${s}`);
    if (stale.length > 10) console.error(`  ... and ${stale.length - 10} more`);
    console.error(`\nRun: node scripts/build-bundles.mjs\n`);
    process.exit(1);
  }
  console.log(`bundles/ up to date (${files.size} files)`);
  process.exit(0);
}

fs.rmSync(BUNDLES, { recursive: true, force: true });
for (const [rel, content] of files) {
  const full = path.join(BUNDLES, rel);
  fs.mkdirSync(path.dirname(full), { recursive: true });
  fs.writeFileSync(full, content);
}

console.log(`\nBuilt bundles/ — ${files.size} files\n${"=".repeat(56)}`);
for (const [key, t] of Object.entries(TARGETS)) {
  const n = [...files.keys()].filter((f) => f.startsWith(key + "/")).length;
  console.log(`  ${t.label.padEnd(13)} bundles/${key.padEnd(12)} ${String(n).padStart(4)} files   copy into ${t.copyInto}${t.verified ? "" : "   [UNVERIFIED]"}`);
}
console.log("");
